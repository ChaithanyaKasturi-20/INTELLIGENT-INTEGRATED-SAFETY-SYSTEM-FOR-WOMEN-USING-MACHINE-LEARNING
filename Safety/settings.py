import os
import sys
from urllib.parse import urlsplit

from django.core.exceptions import ImproperlyConfigured

# Build paths inside the project like this: os.path.join(BASE_DIR, ...)
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

if 'check_exotel_config' not in sys.argv[1:]:
    _local_env_path = os.path.join(BASE_DIR, '.env')
    if os.path.isfile(_local_env_path):
        with open(_local_env_path, 'r', encoding='utf-8') as _local_env_file:
            for _line in _local_env_file:
                _line = _line.strip()
                if _line and not _line.startswith('#') and '=' in _line:
                    _key, _value = _line.split('=', 1)
                    if _key.strip() in {
                        'DJANGO_ENV',
                        'DJANGO_DEBUG',
                        'DJANGO_SECRET_KEY',
                        'SOS_PUBLIC_BASE_URL',
                    }:
                        os.environ.setdefault(
                            _key.strip(),
                            _value.strip().strip('"').strip("'"),
                        )

DJANGO_ENV = os.environ.get('DJANGO_ENV', 'development').strip().lower()
if DJANGO_ENV not in ('development', 'production'):
    raise ImproperlyConfigured(
        'DJANGO_ENV must be either "development" or "production".'
    )

_debug_value = os.environ.get('DJANGO_DEBUG')
if _debug_value is None:
    DEBUG = DJANGO_ENV != 'production'
else:
    _normalized_debug_value = _debug_value.strip().lower()
    if _normalized_debug_value not in (
        'true',
        'false',
        '1',
        '0',
        'yes',
        'no',
        'on',
        'off',
    ):
        raise ImproperlyConfigured(
            'DJANGO_DEBUG must be a boolean value.'
        )
    DEBUG = _normalized_debug_value in ('true', '1', 'yes', 'on')

SECRET_KEY = os.environ.get('DJANGO_SECRET_KEY')
if not SECRET_KEY:
    if DJANGO_ENV == 'production':
        raise ImproperlyConfigured(
            'DJANGO_SECRET_KEY must be configured in production.'
        )
    SECRET_KEY = 'django-insecure-local-development-only-not-for-production'

SOS_PUBLIC_BASE_URL = os.environ.get('SOS_PUBLIC_BASE_URL', '').strip().rstrip('/')
_sos_public_host = ''
try:
    _sos_public_origin = urlsplit(SOS_PUBLIC_BASE_URL)
    if (
        _sos_public_origin.scheme == 'https'
        and _sos_public_origin.hostname
        and _sos_public_origin.path in ('', '/')
        and not _sos_public_origin.username
        and not _sos_public_origin.password
        and not _sos_public_origin.query
        and not _sos_public_origin.fragment
    ):
        _sos_public_host = _sos_public_origin.hostname
except ValueError:
    pass

ALLOWED_HOSTS = [
    'intelligent-integrated-safety-system-for.onrender.com',
    'localhost',
    '127.0.0.1',
]
if _sos_public_host and _sos_public_host not in ALLOWED_HOSTS:
    ALLOWED_HOSTS.append(_sos_public_host)


